"""Measure how well search finds the right papers for a set of test questions.

Run it with:  python -m papertrail.evaluate
Writes a report to eval/RESULTS.md.

Each test question in eval/questions.json lists the papers a good search should return. Metrics:
- Hit@k:    share of questions where at least one right paper is in the top k
- Recall@k: share of all right papers that appear in the top k
- MRR:      mean of 1/rank of the first right paper (1.0 = always ranked first; 0 if not in the top 20)
"""

import argparse
import json
from datetime import date

from papertrail.config import DATA_DIR, ROOT
from papertrail.merge import normalize_title
from papertrail.search import search

QUESTIONS_FILE = ROOT / "eval" / "questions.json"
REPORT_FILE = ROOT / "eval" / "RESULTS.md"
DEPTH = 20  # how far down the ranking to look for MRR


def load_questions() -> list[dict]:
    with QUESTIONS_FILE.open() as f:
        return json.load(f)


def indexed_titles() -> set[str]:
    with (DATA_DIR / "papers.jsonl").open() as f:
        return {normalize_title(json.loads(line)["title"]) for line in f if line.strip()}


def score_question(ranked_titles: list[str], relevant: list[str], k: int) -> dict:
    """Score one question given the titles search returned, best first."""
    wanted = {normalize_title(t) for t in relevant}
    ranked = [normalize_title(t) for t in ranked_titles]
    found_in_top_k = wanted & set(ranked[:k])
    first_rank = next((i + 1 for i, t in enumerate(ranked) if t in wanted), None)
    return {
        "hit": bool(found_in_top_k),
        "recall": len(found_in_top_k) / len(wanted),
        "reciprocal_rank": 1 / first_rank if first_rank else 0.0,
        "first_rank": first_rank,
    }


def evaluate(k: int = 5) -> tuple[dict, list[dict]]:
    available = indexed_titles()
    rows = []
    for item in load_questions():
        missing = [t for t in item["relevant"] if normalize_title(t) not in available]
        if missing:
            print(f"Warning: not in the dataset, ignoring: {missing}")
        relevant = [t for t in item["relevant"] if t not in missing]
        if not relevant:
            continue

        results = search(item["question"], DEPTH)
        scores = score_question([p["title"] for p in results], relevant, k)
        rows.append({**item, "relevant": relevant, **scores, "top": [p["title"] for p in results[:k]]})

    count = len(rows)
    summary = {
        "questions": count,
        "k": k,
        "hit_at_k": sum(r["hit"] for r in rows) / count,
        "recall_at_k": sum(r["recall"] for r in rows) / count,
        "mrr": sum(r["reciprocal_rank"] for r in rows) / count,
    }
    return summary, rows


def write_report(summary: dict, rows: list[dict]) -> None:
    k = summary["k"]
    lines = [
        "# Search quality results",
        "",
        f"Generated by `python -m papertrail.evaluate` on {date.today().isoformat()} "
        f"over {summary['questions']} test questions from `eval/questions.json`.",
        "",
        "| Metric | Score | Meaning |",
        "|---|---|---|",
        f"| Hit@{k} | {summary['hit_at_k']:.0%} | Questions with at least one right paper in the top {k} |",
        f"| Recall@{k} | {summary['recall_at_k']:.0%} | Right papers that made the top {k} |",
        f"| MRR | {summary['mrr']:.2f} | 1.0 means the first right paper is always ranked #1 |",
        "",
        "## Per question",
        "",
        f"| Question | First right paper at rank | Recall@{k} |",
        "|---|---|---|",
    ]
    for r in rows:
        rank = f"#{r['first_rank']}" if r["first_rank"] else f"not in top {DEPTH}"
        lines.append(f"| {r['question']} | {rank} | {r['recall']:.0%} |")

    misses = [r for r in rows if not r["hit"]]
    if misses:
        lines += ["", f"## Misses (no right paper in the top {k})", ""]
        for r in misses:
            lines += [f"**{r['question']}**", "", "Expected: " + "; ".join(r["relevant"]), "", "Got instead:"]
            lines += [f"{i}. {title}" for i, title in enumerate(r["top"], 1)] + [""]

    REPORT_FILE.write_text("\n".join(lines).rstrip() + "\n")
    print(f"Report written to {REPORT_FILE}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Evaluate search quality.")
    parser.add_argument("--k", type=int, default=5, help="how many top results count")
    args = parser.parse_args()

    summary, rows = evaluate(args.k)
    for r in rows:
        rank = f"#{r['first_rank']}" if r["first_rank"] else "miss"
        print(f"{rank:>5}  {r['question']}")
    print(
        f"\nHit@{args.k}: {summary['hit_at_k']:.0%}   Recall@{args.k}: {summary['recall_at_k']:.0%}   "
        f"MRR: {summary['mrr']:.2f}   ({summary['questions']} questions)"
    )
    write_report(summary, rows)
